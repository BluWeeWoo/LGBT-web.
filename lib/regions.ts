const display = new Intl.DisplayNames(["en"], { type: "region" });
const normalize = (value: string) =>
  value
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim()
    .toLowerCase();
const regions = Object.keys(centers).map((code) => ({
  code,
  name: display.of(code) || code,
}));
export const regionNames = regions
  .map((r) => r.name)
  .sort((a, b) => a.localeCompare(b, "en"));
const lookup = new Map(
  regions.map((r) => [normalize(r.name), centers[r.code]]),
);
export function regionCenter(place: string) {
  return lookup.get(normalize(place)) || centers[place.trim().toUpperCase()];
}
